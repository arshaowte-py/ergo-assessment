#!/usr/bin/env node
/**
 * Pull every <style> block out of portal/index.html and freeze it into
 * lib/report-css.generated.ts, so server-rendered PDFs use the exact same CSS
 * the portal's own print window uses.
 *
 * Re-run after any styling change to the portal:  npm run sync:report-css
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const source = resolve(root, "portal/index.html");
const target = resolve(root, "lib/report-css.generated.ts");

const html = readFileSync(source, "utf8");

const blocks = [...html.matchAll(/<style[^>]*>([\s\S]*?)<\/style>/gi)].map((m) => m[1]);
if (!blocks.length) {
  console.error(`No <style> blocks found in ${source}`);
  process.exit(1);
}

// The portal hides everything except the report overlay while previewing.
// That rule would blank the PDF, so drop it — same thing openPrintWindow() does.
const css = blocks
  .join("\n")
  .replace(/body\s*>\s*\*\s*:not\(\s*#reportOverlay\s*\)\s*\{[^}]*\}/g, "")
  .trim();

const banner = `// AUTO-GENERATED by scripts/extract-report-css.mjs — do not edit by hand.
// Source: portal/index.html (${blocks.length} <style> block(s), ${css.length} chars)
// Regenerate with: npm run sync:report-css
`;

writeFileSync(
  target,
  `${banner}\nexport const PORTAL_CSS = ${JSON.stringify(css)};\n`,
  "utf8",
);

console.log(`Wrote ${target} (${css.length} chars of CSS from ${blocks.length} block(s))`);
